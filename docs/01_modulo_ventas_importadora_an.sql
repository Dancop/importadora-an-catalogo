begin;

create extension if not exists pgcrypto;

-- ------------------------------------------------------------
-- 1. TABLA PRINCIPAL DE VENTAS
-- ------------------------------------------------------------

create table if not exists public.ventas (
    id uuid primary key default gen_random_uuid(),
    numero bigint generated by default as identity unique,
    fecha timestamptz not null default now(),

    cliente_nombre text,
    cliente_telefono text,
    metodo_pago text,
    observacion text,

    estado text not null default 'completada'
        check (estado in ('pendiente', 'completada', 'anulada')),

    total_venta numeric(12,2) not null default 0
        check (total_venta >= 0),

    total_costo_proveedor numeric(12,2) not null default 0
        check (total_costo_proveedor >= 0),

    total_otros_gastos numeric(12,2) not null default 0
        check (total_otros_gastos >= 0),

    total_ganancia numeric(12,2) not null default 0,

    creado_por uuid not null default auth.uid()
        references auth.users(id),

    creado_en timestamptz not null default now(),

    anulada_por uuid references auth.users(id),
    anulada_en timestamptz,
    motivo_anulacion text
);

comment on table public.ventas is
'Cabecera de cada venta. Los totales se calculan desde sus detalles y quedan congelados históricamente.';


-- ------------------------------------------------------------
-- 2. DETALLE DE PRODUCTOS VENDIDOS
-- ------------------------------------------------------------

create table if not exists public.detalle_ventas (
    id uuid primary key default gen_random_uuid(),

    venta_id uuid not null
        references public.ventas(id)
        on delete restrict,

    sku text not null
        references public.productos_publicos(sku)
        on update cascade
        on delete restrict,

    -- Copias históricas para no alterar ventas anteriores
    producto_nombre text not null,
    codigo_modelo text,
    color_caja text,
    imagen_principal text,

    tipo_precio text not null
        check (tipo_precio in ('minorista', 'mayorista', 'personalizado')),

    cantidad integer not null
        check (cantidad > 0),

    precio_sugerido_unitario numeric(12,2) not null
        check (precio_sugerido_unitario >= 0),

    precio_venta_unitario numeric(12,2) not null
        check (precio_venta_unitario >= 0),

    precio_base_historico numeric(12,2) not null
        check (precio_base_historico >= 0),

    factor_costo_historico numeric(12,4) not null
        check (factor_costo_historico >= 0),

    costo_proveedor_unitario numeric(12,2) not null
        check (costo_proveedor_unitario >= 0),

    otros_gastos numeric(12,2) not null default 0
        check (otros_gastos >= 0),

    subtotal numeric(12,2)
        generated always as (
            round(cantidad * precio_venta_unitario, 2)
        ) stored,

    descuento_total numeric(12,2)
        generated always as (
            round(
                greatest(
                    (cantidad * precio_sugerido_unitario)
                    - (cantidad * precio_venta_unitario),
                    0
                ),
                2
            )
        ) stored,

    costo_proveedor_total numeric(12,2)
        generated always as (
            round(cantidad * costo_proveedor_unitario, 2)
        ) stored,

    ganancia_real numeric(12,2)
        generated always as (
            round(
                (cantidad * precio_venta_unitario)
                - (cantidad * costo_proveedor_unitario)
                - otros_gastos,
                2
            )
        ) stored,

    creado_en timestamptz not null default now()
);

create index if not exists detalle_ventas_venta_id_idx
    on public.detalle_ventas(venta_id);

create index if not exists detalle_ventas_sku_idx
    on public.detalle_ventas(sku);

comment on table public.detalle_ventas is
'Productos incluidos en una venta. Guarda precio base, factor, costo y precio real como fotografía histórica.';


-- ------------------------------------------------------------
-- 3. MOVIMIENTOS DE INVENTARIO
-- ------------------------------------------------------------

create table if not exists public.movimientos_inventario (
    id uuid primary key default gen_random_uuid(),

    sku text not null
        references public.productos_publicos(sku)
        on update cascade
        on delete restrict,

    venta_id uuid
        references public.ventas(id)
        on delete restrict,

    tipo text not null
        check (tipo in (
            'venta',
            'anulacion_venta',
            'ajuste_entrada',
            'ajuste_salida'
        )),

    cantidad integer not null
        check (cantidad <> 0),

    stock_anterior integer not null,
    stock_nuevo integer not null
        check (stock_nuevo >= 0),

    observacion text,

    creado_por uuid not null default auth.uid()
        references auth.users(id),

    creado_en timestamptz not null default now()
);

create index if not exists movimientos_inventario_sku_idx
    on public.movimientos_inventario(sku);

create index if not exists movimientos_inventario_venta_id_idx
    on public.movimientos_inventario(venta_id);


-- ------------------------------------------------------------
-- 4. LIQUIDACIONES ENTREGADAS AL PROVEEDOR
-- ------------------------------------------------------------

create table if not exists public.liquidaciones_proveedor (
    id uuid primary key default gen_random_uuid(),
    fecha timestamptz not null default now(),

    monto numeric(12,2) not null
        check (monto > 0),

    metodo_pago text,
    referencia text,
    observacion text,
    comprobante_url text,

    estado text not null default 'registrada'
        check (estado in ('registrada', 'anulada')),

    creado_por uuid not null default auth.uid()
        references auth.users(id),

    creado_en timestamptz not null default now(),

    anulada_por uuid references auth.users(id),
    anulada_en timestamptz,
    motivo_anulacion text
);

create index if not exists liquidaciones_proveedor_fecha_idx
    on public.liquidaciones_proveedor(fecha);


